    const color = tailMatch[5].trim();
    const kmStr = tailMatch[6].replace(/\./g, '');
    const kilometraje = parseInt(kmStr, 10);
    const empresa = tailMatch[7].trim();
    const precioStr = tailMatch[8].replace(/\./g, '');
    const precio = parseInt(precioStr, 10);
    const fechaToma = tailMatch[9].trim();

    // Now everything before the tail match is: [prefix/category] + [unidad/modelo/version]
    const head = rest.slice(0, rest.length - tailMatch[0].length).trim();

    // Prefix/Category at the beginning of head:
    // Can be: 'P - PA 0 KM', 'PA 0 KM', '0 KM', 'P - A', 'P - T', 'P - C', 'PA', 'TS', 'P - AK', 'P - PA', 'P - AR', 'FLOTA', 'AK', 'T', 'C', 'A'
    let categoriaParts = [];
    let remainingHead = head;

    // Check if starts with P - XX or PA or TS or FLOTA or AK or T or C or A
    const pMatch = remainingHead.match(/^(P\s*-\s*[A-Z]+|FLOTA|AK|TS|PA|T|C|A)\s+/i);
    if (pMatch) {
      categoriaParts.push(pMatch[1].trim());
      remainingHead = remainingHead.slice(pMatch[0].length).trim();
    }

    // Check if next is 0 KM
    const zeroKmMatch = remainingHead.match(/^(0\s*KM)\s+/i);
    if (zeroKmMatch) {
      categoriaParts.push('0 KM');
      remainingHead = remainingHead.slice(zeroKmMatch[0].length).trim();
    }

    // Also check if started with 0 KM first
    if (categoriaParts.length === 0) {
      const zMatch = remainingHead.match(/^(0\s*KM)\s+/i);
      if (zMatch) {
        categoriaParts.push('0 KM');
        remainingHead = remainingHead.slice(zMatch[0].length).trim();
      }
    }

    const categoria = categoriaParts.join(' ');
